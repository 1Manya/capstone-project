"""
dataloader.py
-------------
PyTorch Dataset and DataLoader for the laser attack detection project.

Reads from data/final_dataset/labels.csv, as generated by the v7
dataset_builder.py / rolling_shutter_simulator_v7.py pipeline.

WHAT CHANGED FROM THE PREVIOUS VERSION (and why):

1. labels.csv no longer has a binary 0/1 "label" column - it has a
   descriptive string label (e.g. "clean", "attack_low", "attack_mid",
   "attack_full_range" - whatever you named things in `variations:` in
   config.yaml). Binary attack/clean is now derived here, from the
   `variation` column: variation == "clean" -> 0, anything else -> 1.
   The original string label is kept alongside (as `variation_name`) so
   you still have it for analysis/confusion matrices, but the CNN target
   is always the binary int.

2. `cfg["dataset"]["variations"]` (a dict) no longer exists in the v7
   config - variations now live at the top level, `cfg["variations"]`,
   as a LIST of dicts (each with a "name" key). get_variation_names()
   is updated to read that shape. If your config still has an old-style
   `dataset.variations` dict somewhere for other purposes, this file
   ignores it and reads only the top-level `variations:` list that
   dataset_builder.py actually uses to generate images.

3. image_size / batch_size / num_workers / pin_memory are NOT part of
   the v7 simulator config (that config only covers physics + paths).
   Those are CNN/training concerns, so this file expects them under a
   `training:` section you add to config.yaml yourself (see the
   `training:` block appended to simulator_config_v7.yaml). Defaults are
   provided here so this still runs even if you haven't added that
   section yet.

Usage:
    from src.dataset.dataloader import get_dataloaders
    loaders = get_dataloaders(cfg)
    train_loader = loaders["train"]
"""

import os
import csv
from pathlib import Path
from typing import Dict, Optional

import torch
from torch.utils.data import Dataset, DataLoader
from torchvision import transforms
from PIL import Image


# ImageNet mean/std - standard for ResNet pretrained weights
IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]

DEFAULT_IMAGE_SIZE = 224
DEFAULT_BATCH_SIZE = 32
DEFAULT_NUM_WORKERS = 4


def get_transforms(split: str, image_size: int):
    """Returns torchvision transform pipeline for train / val+test."""
    if split == "train":
        return transforms.Compose([
            transforms.Resize((image_size + 16, image_size + 16)),
            transforms.RandomCrop(image_size),
            transforms.RandomHorizontalFlip(p=0.5),
            transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.1),
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ])
    else:
        return transforms.Compose([
            transforms.Resize((image_size, image_size)),
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ])


class LaserAttackDataset(Dataset):
    """
    Binary image classification dataset (clean vs attacked).

    The v7 dataset builder writes a descriptive string label per variation
    (e.g. "attack_mid"), not a binary 0/1. This class derives the binary
    target itself from the `variation` column: variation == "clean" -> 0,
    anything else -> 1. The original string is kept as `variation_name` on
    each sample for analysis, but never used as the training target.

    Args:
        csv_path        : Path to labels.csv
        dataset_root    : Root folder (labels.csv paths are relative to this)
        split           : "train" | "val" | "test"
        transform       : torchvision transform
        variation_filter: If set, only load samples of this variation name
                           PLUS clean samples (e.g. "freq_mid_narrow" for a
                           specialist ensemble head). Set to None for all
                           attack variations + clean.
    """

    def __init__(
        self,
        csv_path: str,
        dataset_root: str,
        split: str,
        transform,
        variation_filter: Optional[str] = None,
    ):
        self.dataset_root = dataset_root
        self.transform = transform
        self.samples = []  # list of (abs_path, binary_label, variation_name)

        with open(csv_path, newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row["split"] != split:
                    continue
                variation = row["variation"]
                if variation_filter is not None:
                    # Keep clean samples + only the target variation
                    if variation != "clean" and variation != variation_filter:
                        continue
                binary_label = 0 if variation == "clean" else 1
                abs_path = os.path.join(dataset_root, row["path"])
                self.samples.append((abs_path, binary_label, variation))

        if len(self.samples) == 0:
            raise ValueError(
                f"No samples found for split='{split}', variation='{variation_filter}'.\n"
                "Run dataset_builder.py first to generate the dataset."
            )

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        path, label, variation = self.samples[idx]
        img = Image.open(path).convert("RGB")
        if self.transform:
            img = self.transform(img)
        return img, label

    def get_class_weights(self):
        """Compute class weights for imbalanced training (used by focal/weighted loss)."""
        labels = [s[1] for s in self.samples]
        n_total = len(labels)
        n_pos = sum(labels)
        n_neg = n_total - n_pos
        w_neg = n_total / (2 * max(1, n_neg))
        w_pos = n_total / (2 * max(1, n_pos))
        return torch.tensor([w_neg, w_pos], dtype=torch.float32)


def _training_cfg(cfg: dict) -> dict:
    """Pull training-loader params from cfg['training'] if present, else defaults.
    The v7 simulator config only covers physics/paths - add a `training:` block
    (image_size/batch_size/num_workers/pin_memory) to your config.yaml if you
    want to control these; otherwise sane defaults are used."""
    t = cfg.get("training", {})
    return {
        "image_size": t.get("image_size", DEFAULT_IMAGE_SIZE),
        "batch_size": t.get("batch_size", DEFAULT_BATCH_SIZE),
        "num_workers": t.get("num_workers", DEFAULT_NUM_WORKERS),
        "pin_memory": t.get("pin_memory", True),
    }


def get_dataloaders(cfg: dict, variation_filter: Optional[str] = None) -> Dict[str, DataLoader]:
    """
    Build train, val, test DataLoaders from config.

    Args:
        cfg              : full config dict loaded from config.yaml
        variation_filter : if set, builds specialist dataloaders for ensemble
    """
    paths_cfg = cfg["paths"]
    train_cfg = _training_cfg(cfg)

    dataset_root = paths_cfg["final_dataset"]
    csv_path = os.path.join(dataset_root, "labels.csv")
    image_size = train_cfg["image_size"]

    loaders = {}
    for split in ["train", "val", "test"]:
        tfm = get_transforms(split, image_size)
        dataset = LaserAttackDataset(
            csv_path=csv_path,
            dataset_root=dataset_root,
            split=split,
            transform=tfm,
            variation_filter=variation_filter,
        )
        shuffle = (split == "train")
        loader = DataLoader(
            dataset,
            batch_size=train_cfg["batch_size"],
            shuffle=shuffle,
            num_workers=train_cfg["num_workers"],
            pin_memory=train_cfg["pin_memory"],
            drop_last=(split == "train"),
        )
        loaders[split] = loader

    # Log sizes
    for split, loader in loaders.items():
        n = len(loader.dataset)
        labels = [s[1] for s in loader.dataset.samples]
        n_pos = sum(labels)
        print(f"  [{split:5s}] {n:5d} samples | clean: {n - n_pos} | attacked: {n_pos}")

    return loaders


def get_variation_names(cfg: dict) -> list:
    """Return list of attack variation names from config (excludes 'clean').
    Reads the top-level `variations:` list that dataset_builder.py uses,
    not a `dataset.variations` dict - that key no longer exists in v7."""
    return [v["name"] for v in cfg["variations"] if not v.get("clean", False)]