#!/usr/bin/env python3
"""
Frequency-specialised CNN ensemble + SSD feature fusion.

Expected inputs:
  1) labels_paired.csv with: path, variation, source_clean_image
  2) detection_features.csv generated by extract_detection_features.py with:
     path, num_detections, mean_confidence, max_confidence,
     std_confidence, low_conf_count

The script:
  - splits by source_clean_image to prevent scene leakage;
  - trains one balanced ResNet18 specialist for each configured attack variation
    (each specialist sees CLEAN + only its own attack variation);
  - averages the five specialist attack probabilities;
  - trains a final MLP fusion classifier on the five probabilities plus SSD
    detection statistics;
  - evaluates once on a held-out test split.

IMPORTANT:
  The detection feature CSV must cover the same labelled images used here.
  Generate it from the complete labels_paired.csv (or a deliberate subset).
  Never use the external real-world test set to train or tune this pipeline.
"""

import argparse
import copy
import json
import random
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
import yaml
from sklearn.metrics import (
    accuracy_score, balanced_accuracy_score, confusion_matrix, f1_score,
    precision_score, recall_score, roc_auc_score
)
from torch.utils.data import Dataset, DataLoader, WeightedRandomSampler
from torchvision import models

DET_COLS = [
    "num_detections", "mean_confidence", "max_confidence",
    "std_confidence", "low_conf_count"
]
LOG_COLS = {"num_detections", "low_conf_count"}
IMAGENET_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
IMAGENET_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def norm_path(x):
    return str(x).replace("\\", "/").strip()


def resolve_project_paths(config_path, cfg):
    project_root = config_path.resolve().parent.parent
    dataset_root = (project_root / cfg["paths"]["final_dataset"]).resolve()
    return project_root, dataset_root


def group_split(df, cfg, seed):
    """Split source backgrounds, not individual images, to avoid scene leakage."""
    split_cfg = cfg["split"]
    fractions = [
        float(split_cfg["specialist_train"]),
        float(split_cfg["specialist_val"]),
        float(split_cfg["fusion_train"]),
        float(split_cfg["fusion_val"]),
        float(split_cfg["test"]),
    ]
    if not np.isclose(sum(fractions), 1.0):
        raise ValueError(f"Split fractions must sum to 1.0; got {sum(fractions):.4f}")

    groups = np.array(df["source_clean_image"].dropna().unique(), dtype=object)
    rng = np.random.default_rng(seed)
    rng.shuffle(groups)
    n = len(groups)
    cuts = np.cumsum([int(round(f * n)) for f in fractions[:-1]])
    chunks = np.split(groups, cuts)
    names = ["specialist_train", "specialist_val", "fusion_train", "fusion_val", "test"]
    mapping = {g: name for name, chunk in zip(names, chunks) for g in chunk}
    out = df.copy()
    out["part"] = out["source_clean_image"].map(mapping)
    if out["part"].isna().any():
        raise RuntimeError("Some rows could not be assigned to a split.")
    sets = {k: set(out.loc[out.part == k, "source_clean_image"]) for k in names}
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if sets[a] & sets[b]:
                raise RuntimeError(f"Background leakage between {a} and {b}")
    return out


def make_det_matrix(df):
    x = df[DET_COLS].astype(float).fillna(0.0).copy()
    for c in LOG_COLS:
        x[c] = np.log1p(x[c].clip(lower=0))
    return x.to_numpy(dtype=np.float32)


class ImageTable(Dataset):
    def __init__(self, df, dataset_root, image_size):
        self.df = df.reset_index(drop=True)
        self.root = Path(dataset_root)
        self.image_size = int(image_size)

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        p = self.root / norm_path(row["path"])
        image = cv2.imread(str(p))
        if image is None:
            raise FileNotFoundError(f"Could not read image: {p}")
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
        image = cv2.resize(image, (self.image_size, self.image_size))
        image = image.astype(np.float32) / 255.0
        image = (image - IMAGENET_MEAN) / IMAGENET_STD
        image = torch.from_numpy(np.ascontiguousarray(image.transpose(2, 0, 1)))
        return image, int(row["is_attacked"])


def make_balanced_loader(df, dataset_root, cfg, shuffle):
    ds = ImageTable(df, dataset_root, cfg["training"]["image_size"])
    labels = df["is_attacked"].astype(int).to_numpy()
    counts = np.bincount(labels, minlength=2).astype(np.float64)
    if (counts == 0).any():
        raise ValueError(f"Both classes are required; class counts={counts.tolist()}")
    sample_weights = np.array([1.0 / counts[y] for y in labels], dtype=np.float64)
    sampler = WeightedRandomSampler(
        torch.as_tensor(sample_weights, dtype=torch.double),
        num_samples=len(sample_weights),
        replacement=True
    ) if shuffle else None

    return DataLoader(
        ds,
        batch_size=int(cfg["training"]["batch_size"]),
        shuffle=(shuffle and sampler is None),
        sampler=sampler,
        num_workers=int(cfg["training"]["num_workers"]),
        pin_memory=bool(cfg["training"].get("pin_memory", True)),
        drop_last=False,
        persistent_workers=int(cfg["training"]["num_workers"]) > 0
    )


def make_resnet(pretrained=True, dropout=0.3):
    weights = models.ResNet18_Weights.DEFAULT if pretrained else None
    net = models.resnet18(weights=weights)
    in_features = net.fc.in_features
    net.fc = nn.Sequential(nn.Dropout(dropout), nn.Linear(in_features, 2))
    return net


def run_epoch(model, loader, device, criterion, optimizer=None):
    training = optimizer is not None
    model.train(training)
    loss_total, n_total = 0.0, 0
    all_logits, all_y = [], []
    with torch.set_grad_enabled(training):
        for x, y in loader:
            x = x.to(device, non_blocking=True)
            y = y.to(device, non_blocking=True)
            logits = model(x)
            loss = criterion(logits, y)
            if training:
                optimizer.zero_grad(set_to_none=True)
                loss.backward()
                optimizer.step()
            loss_total += loss.item() * len(y)
            n_total += len(y)
            all_logits.append(logits.detach().cpu().numpy())
            all_y.append(y.detach().cpu().numpy())
    return loss_total / max(n_total, 1), np.concatenate(all_logits), np.concatenate(all_y)


def probs_from_logits(logits):
    z = logits - logits.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e[:, 1] / e.sum(axis=1)


def train_specialist(name, attack_variation, parts, dataset_root, cfg, out_dir, device):
    tr = parts["specialist_train"]
    va = parts["specialist_val"]
    tr = tr[(tr.variation == "clean") | (tr.variation == attack_variation)].copy()
    va = va[(va.variation == "clean") | (va.variation == attack_variation)].copy()

    # Explicitly balance each specialist's training set by downsampling the larger class.
    rng = np.random.default_rng(int(cfg["training"]["seed"]) + sum(map(ord, name)))
    clean = tr[tr.is_attacked == 0]
    attack = tr[tr.is_attacked == 1]
    n = min(len(clean), len(attack))
    if n == 0:
        raise ValueError(f"{name}: no clean/attack pairs available. clean={len(clean)}, attack={len(attack)}")
    clean = clean.iloc[rng.choice(len(clean), n, replace=False)]
    attack = attack.iloc[rng.choice(len(attack), n, replace=False)]
    tr = pd.concat([clean, attack]).sample(frac=1, random_state=int(cfg["training"]["seed"]))

    print(f"\n[{name}] train={len(tr)} (clean={n}, attack={n}), val={len(va)}", flush=True)
    train_loader = make_balanced_loader(tr, dataset_root, cfg, shuffle=True)
    val_loader = make_balanced_loader(va, dataset_root, cfg, shuffle=False)

    model = make_resnet(
        pretrained=bool(cfg["model"]["pretrained"]),
        dropout=float(cfg["model"]["dropout"])
    ).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=float(cfg["training"]["learning_rate"]),
        weight_decay=float(cfg["training"]["weight_decay"])
    )
    criterion = nn.CrossEntropyLoss()
    best_auc, best_state, best_epoch, bad_epochs = -1.0, None, 0, 0
    epochs = int(cfg["training"]["epochs"])
    patience = int(cfg["training"]["patience"])

    for epoch in range(1, epochs + 1):
        train_loss, _, _ = run_epoch(model, train_loader, device, criterion, optimizer)
        val_loss, val_logits, val_y = run_epoch(model, val_loader, device, criterion)
        val_p = probs_from_logits(val_logits)
        auc = roc_auc_score(val_y, val_p) if len(np.unique(val_y)) == 2 else float("nan")
        print(f"[{name}] epoch {epoch}/{epochs} train_loss={train_loss:.4f} "
              f"val_loss={val_loss:.4f} val_auc={auc:.4f}", flush=True)

        score = auc if np.isfinite(auc) else -val_loss
        if score > best_auc:
            best_auc, best_state, best_epoch, bad_epochs = score, copy.deepcopy(model.state_dict()), epoch, 0
        else:
            bad_epochs += 1

        if bad_epochs >= patience:
            print(f"[{name}] early stopping at epoch {epoch}", flush=True)
            break

    if best_state is None:
        raise RuntimeError(f"{name}: no valid checkpoint produced.")
    model.load_state_dict(best_state)
    ckpt_path = out_dir / f"{name}.pt"
    torch.save({
        "model_state_dict": best_state,
        "attack_variation": attack_variation,
        "image_size": int(cfg["training"]["image_size"]),
        "best_epoch": best_epoch,
        "best_val_auc": float(best_auc),
        "class_names": ["clean", "attacked"],
    }, ckpt_path)
    return model, {"best_epoch": best_epoch, "best_val_auc": float(best_auc), "checkpoint": str(ckpt_path)}


@torch.no_grad()
def predict_specialist(model, df, dataset_root, cfg, device):
    loader = DataLoader(
        ImageTable(df, dataset_root, cfg["training"]["image_size"]),
        batch_size=int(cfg["training"]["batch_size"]),
        shuffle=False,
        num_workers=int(cfg["training"]["num_workers"]),
        pin_memory=bool(cfg["training"].get("pin_memory", True))
    )
    model.eval()
    out = []
    for x, _ in loader:
        logits = model(x.to(device, non_blocking=True))
        out.extend(probs_from_logits(logits.cpu().numpy()).tolist())
    return np.asarray(out, dtype=np.float32)


class FusionMLP(nn.Module):
    def __init__(self, input_dim, hidden_dim=32, dropout=0.2):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 16),
            nn.ReLU(),
            nn.Linear(16, 2)
        )

    def forward(self, x):
        return self.net(x)


def classification_metrics(y, p, threshold=0.5):
    pred = (p >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "n": int(len(y)),
        "accuracy": float(accuracy_score(y, pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y, pred)),
        "roc_auc": float(roc_auc_score(y, p)) if len(np.unique(y)) == 2 else None,
        "precision_attacked": float(precision_score(y, pred, zero_division=0)),
        "recall_attacked": float(recall_score(y, pred, zero_division=0)),
        "specificity_clean": float(tn / (tn + fp)) if (tn + fp) else None,
        "f1_attacked": float(f1_score(y, pred, zero_division=0)),
        "tp": int(tp), "tn": int(tn), "fp": int(fp), "fn": int(fn),
    }


def balanced_tensor_loader(x, y, batch_size):
    counts = np.bincount(y, minlength=2).astype(np.float64)
    if (counts == 0).any():
        raise ValueError(f"Fusion training requires both classes; counts={counts.tolist()}")
    weights = np.array([1.0 / counts[int(label)] for label in y], dtype=np.float64)
    sampler = WeightedRandomSampler(torch.tensor(weights, dtype=torch.double), len(weights), replacement=True)
    ds = torch.utils.data.TensorDataset(torch.tensor(x, dtype=torch.float32), torch.tensor(y, dtype=torch.long))
    return DataLoader(ds, batch_size=batch_size, sampler=sampler)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True, help="Path to ensemble_config.yaml")
    ap.add_argument("--labels", required=True, help="labels_paired.csv")
    ap.add_argument("--det_features", required=True, help="CSV from extract_detection_features.py")
    ap.add_argument("--out_dir", default=None)
    ap.add_argument("--limit", type=int, default=None, help="small debug subset; do not use for final results")
    args = ap.parse_args()

    config_path = Path(args.config).resolve()
    cfg = yaml.safe_load(config_path.read_text())
    project_root, dataset_root = resolve_project_paths(config_path, cfg)
    out_dir = Path(args.out_dir or (project_root / cfg["paths"]["output_dir"])).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    seed = int(cfg["training"]["seed"])
    seed_everything(seed)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Device: {device}")
    if torch.cuda.is_available():
        print(f"GPU: {torch.cuda.get_device_name(0)}")

    labels = pd.read_csv(args.labels)
    required_labels = {"path", "variation", "source_clean_image"}
    missing = required_labels - set(labels.columns)
    if missing:
        raise ValueError(f"Labels CSV missing required columns: {sorted(missing)}")
    labels["path_key"] = labels["path"].map(norm_path)
    labels["source_clean_image"] = labels["source_clean_image"].map(norm_path)
    labels["is_attacked"] = (labels["variation"].astype(str) != "clean").astype(int)
    labels = labels.drop_duplicates("path_key")

    det = pd.read_csv(args.det_features)
    if "path" not in det.columns:
        raise ValueError("Detection feature CSV must contain a 'path' column.")
    missing_det = set(DET_COLS) - set(det.columns)
    if missing_det:
        raise ValueError(f"Detection feature CSV missing columns: {sorted(missing_det)}")
    det["path_key"] = det["path"].map(norm_path)
    det = det.drop_duplicates("path_key")
    data = labels.merge(det[["path_key"] + DET_COLS], on="path_key", how="inner")
    if len(data) == 0:
        raise ValueError("No rows matched between labels and detection features. Check path formats.")
    if len(data) < len(labels):
        print(f"WARNING: using {len(data)}/{len(labels)} labelled images with SSD features.")
    data["is_attacked"] = data["is_attacked"].astype(int)
    data = data.dropna(subset=["source_clean_image"]).reset_index(drop=True)

    if args.limit:
        data = data.sample(min(args.limit, len(data)), random_state=seed).reset_index(drop=True)

    print("\nMatched data by variation:")
    print(data.groupby("variation").size().to_string())
    parts_df = group_split(data, cfg, seed)
    parts = {name: parts_df[parts_df.part == name].reset_index(drop=True)
             for name in ["specialist_train", "specialist_val", "fusion_train", "fusion_val", "test"]}
    print("\nGroup-disjoint split:")
    for name, part in parts.items():
        print(f"{name:16s}: {len(part):6d} images | {part.source_clean_image.nunique():5d} backgrounds "
              f"| {part.is_attacked.mean():.1%} attacked")

    variations = cfg["specialists"]["variations"]
    specialist_models, specialist_info = {}, {}
    for variation in variations:
        model_name = "cnn_" + variation.replace("freq_", "")
        model, info = train_specialist(
            model_name, variation, parts, dataset_root, cfg, out_dir, device
        )
        specialist_models[variation] = model
        specialist_info[variation] = info

    # The specialists never train on fusion_train/fusion_val/test backgrounds.
    # Their predictions therefore provide leakage-safe inputs for the fusion MLP.
    def specialist_prob_matrix(frame):
        columns = []
        for variation in variations:
            columns.append(predict_specialist(
                specialist_models[variation], frame, dataset_root, cfg, device
            ))
        return np.column_stack(columns).astype(np.float32)

    print("\nGenerating specialist probabilities for fusion datasets...")
    ftr, fva, fte = parts["fusion_train"], parts["fusion_val"], parts["test"]
    p_ftr = specialist_prob_matrix(ftr)
    p_fva = specialist_prob_matrix(fva)
    p_fte = specialist_prob_matrix(fte)

    # Standardise SSD features using fusion-training rows only.
    det_ftr = make_det_matrix(ftr)
    det_mu = det_ftr.mean(axis=0)
    det_sd = det_ftr.std(axis=0)
    det_sd[det_sd < 1e-6] = 1.0
    x_ftr = np.column_stack([p_ftr, (det_ftr - det_mu) / det_sd]).astype(np.float32)
    x_fva = np.column_stack([
        p_fva, (make_det_matrix(fva) - det_mu) / det_sd
    ]).astype(np.float32)
    x_fte = np.column_stack([
        p_fte, (make_det_matrix(fte) - det_mu) / det_sd
    ]).astype(np.float32)
    y_ftr = ftr.is_attacked.to_numpy(dtype=np.int64)
    y_fva = fva.is_attacked.to_numpy(dtype=np.int64)
    y_fte = fte.is_attacked.to_numpy(dtype=np.int64)

    fusion_cfg = cfg["fusion"]
    fusion_model = FusionMLP(
        input_dim=x_ftr.shape[1],
        hidden_dim=int(fusion_cfg["hidden_dim"]),
        dropout=float(fusion_cfg["dropout"])
    ).to(device)
    optimizer = torch.optim.AdamW(
        fusion_model.parameters(),
        lr=float(fusion_cfg["learning_rate"]),
        weight_decay=float(fusion_cfg["weight_decay"])
    )
    train_loader = balanced_tensor_loader(x_ftr, y_ftr, int(fusion_cfg["batch_size"]))
    val_x = torch.tensor(x_fva, dtype=torch.float32, device=device)
    val_y = torch.tensor(y_fva, dtype=torch.long, device=device)
    criterion = nn.CrossEntropyLoss()
    best_auc, best_state, bad = -1.0, None, 0

    print("\nTraining final CNN-ensemble + SSD fusion classifier...")
    for epoch in range(1, int(fusion_cfg["epochs"]) + 1):
        fusion_model.train()
        total_loss, seen = 0.0, 0
        for xb, yb in train_loader:
            xb, yb = xb.to(device), yb.to(device)
            logits = fusion_model(xb)
            loss = criterion(logits, yb)
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            optimizer.step()
            total_loss += loss.item() * len(yb)
            seen += len(yb)

        fusion_model.eval()
        with torch.no_grad():
            val_logits = fusion_model(val_x).cpu().numpy()
        val_p = probs_from_logits(val_logits)
        val_auc = roc_auc_score(y_fva, val_p) if len(np.unique(y_fva)) == 2 else float("nan")
        print(f"[fusion] epoch {epoch}/{fusion_cfg['epochs']} "
              f"train_loss={total_loss/max(seen,1):.4f} val_auc={val_auc:.4f}", flush=True)

        score = val_auc if np.isfinite(val_auc) else -total_loss / max(seen, 1)
        if score > best_auc:
            best_auc, best_state, bad = score, copy.deepcopy(fusion_model.state_dict()), 0
        else:
            bad += 1
        if bad >= int(fusion_cfg["patience"]):
            print("[fusion] early stopping", flush=True)
            break

    if best_state is None:
        raise RuntimeError("Fusion model did not produce a checkpoint.")
    fusion_model.load_state_dict(best_state)
    fusion_model.eval()
    with torch.no_grad():
        test_logits = fusion_model(torch.tensor(x_fte, dtype=torch.float32, device=device)).cpu().numpy()
    test_p = probs_from_logits(test_logits)
    metrics = classification_metrics(y_fte, test_p, threshold=float(cfg["evaluation"]["threshold"]))

    # Also report the simple mean ensemble, before SSD fusion.
    mean_ensemble_p = p_fte.mean(axis=1)
    ensemble_metrics = classification_metrics(
        y_fte, mean_ensemble_p, threshold=float(cfg["evaluation"]["threshold"])
    )

    # Save checkpoints and metadata.
    for variation, model in specialist_models.items():
        model.eval()
    torch.save({
        "state_dict": best_state,
        "input_dim": int(x_ftr.shape[1]),
        "det_mu": det_mu.tolist(),
        "det_sd": det_sd.tolist(),
        "variations": variations,
        "threshold": float(cfg["evaluation"]["threshold"]),
        "class_names": ["clean", "attacked"]
    }, out_dir / "model_fusion_ensemble_ssd.pt")

    torch.save({
        "variations": variations,
        "specialists": {
            v: {
                "checkpoint": specialist_info[v]["checkpoint"],
                "best_epoch": specialist_info[v]["best_epoch"],
                "best_val_auc": specialist_info[v]["best_val_auc"]
            } for v in variations
        },
        "ensemble_method": "arithmetic_mean",
        "fusion_checkpoint": str(out_dir / "model_fusion_ensemble_ssd.pt")
    }, out_dir / "ensemble_manifest.pt")

    pred_df = fte[["path", "variation", "is_attacked", "source_clean_image"]].copy()
    for i, variation in enumerate(variations):
        pred_df[f"p_{variation}"] = p_fte[:, i]
    pred_df["p_cnn_ensemble"] = mean_ensemble_p
    pred_df["p_fusion"] = test_p
    pred_df.to_csv(out_dir / "predictions_test_ensemble_fusion.csv", index=False)

    results = {
        "specialists": specialist_info,
        "cnn_probability_ensemble_test": ensemble_metrics,
        "cnn_ensemble_plus_ssd_fusion_test": metrics,
        "split_counts": {k: int(len(v)) for k, v in parts.items()},
        "notes": [
            "Specialist models train on CLEAN plus one frequency variation each.",
            "Balanced sampling is applied within every specialist.",
            "All splits are grouped by source_clean_image.",
            "Fusion is trained on specialist predictions from backgrounds not used to train the specialists.",
            "The test split is not used for model selection."
        ]
    }
    (out_dir / "metrics_ensemble_fusion.json").write_text(json.dumps(results, indent=2))
    print("\n=== HELD-OUT TEST RESULTS ===")
    print("CNN probability ensemble:")
    print(json.dumps(ensemble_metrics, indent=2))
    print("\nCNN ensemble + SSD fusion:")
    print(json.dumps(metrics, indent=2))
    print(f"\nSaved outputs to: {out_dir}")


if __name__ == "__main__":
    main()
